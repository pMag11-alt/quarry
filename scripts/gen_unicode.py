#!/usr/bin/env python3
"""Generate src/main/resources/quarry/unicode12.dat from the Unicode 12.1
character database: the properties Lucene's StandardTokenizer grammar uses
(it is generated from Unicode 12.1).

Each line is `start end class emoji` in hex, for runs of code points with
the same values:
  class: low 5 bits = Word_Break value (see WordClass.kt), 0x20 = Line_Break
         Complex_Context (SA), 0x40 = Script Han, 0x80 = Script Hiragana
  emoji: 1 Emoji, 4 Emoji_Modifier, 8 Emoji_Modifier_Base,
         16 Extended_Pictographic

    python3 scripts/gen_unicode.py [ucd-dir]
"""

import os
import sys
import urllib.request

BASE = "https://www.unicode.org/Public/"
FILES = {
    "WordBreakProperty.txt": "12.1.0/ucd/auxiliary/WordBreakProperty.txt",
    "LineBreak.txt": "12.1.0/ucd/LineBreak.txt",
    "Scripts.txt": "12.1.0/ucd/Scripts.txt",
    "emoji-data.txt": "emoji/12.1/emoji-data.txt",
}
WB = {"ALetter": 1, "Hebrew_Letter": 2, "Numeric": 3, "Katakana": 4, "ExtendNumLet": 5, "MidLetter": 6,
      "MidNum": 7, "MidNumLet": 8, "Single_Quote": 9, "Double_Quote": 10, "Extend": 11, "Format": 12,
      "ZWJ": 13, "Regional_Indicator": 14}
EMOJI = {"Emoji": 1, "Emoji_Modifier": 4, "Emoji_Modifier_Base": 8, "Extended_Pictographic": 16}


def entries(path):
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        cps, value = [x.strip() for x in line.split(";")[:2]]
        lo, _, hi = cps.partition("..")
        yield int(lo, 16), int(hi or lo, 16), value


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/tmp/ucd12"
    os.makedirs(d, exist_ok=True)
    for name, url in FILES.items():
        if not os.path.exists(os.path.join(d, name)):
            urllib.request.urlretrieve(BASE + url, os.path.join(d, name))
    cls = bytearray(0x110000)
    emo = bytearray(0x110000)
    for lo, hi, v in entries(os.path.join(d, "WordBreakProperty.txt")):
        if v in WB:
            for cp in range(lo, hi + 1):
                cls[cp] = (cls[cp] & 0xE0) | WB[v]
    for lo, hi, v in entries(os.path.join(d, "LineBreak.txt")):
        if v == "SA":
            for cp in range(lo, hi + 1):
                cls[cp] |= 0x20
    for lo, hi, v in entries(os.path.join(d, "Scripts.txt")):
        if v in ("Han", "Hiragana"):
            for cp in range(lo, hi + 1):
                cls[cp] |= 0x40 if v == "Han" else 0x80
    for lo, hi, v in entries(os.path.join(d, "emoji-data.txt")):
        if v in EMOJI:
            for cp in range(lo, hi + 1):
                emo[cp] |= EMOJI[v]
    out = os.path.join(os.path.dirname(__file__), "..", "src", "main", "resources", "quarry", "unicode12.dat")
    runs = 0
    with open(out, "w") as f:
        f.write("# Generated by scripts/gen_unicode.py from Unicode 12.1. Do not edit.\n")
        start = 0
        for cp in range(1, 0x110001):
            if cp == 0x110000 or cls[cp] != cls[start] or emo[cp] != emo[start]:
                if cls[start] or emo[start]:
                    f.write(f"{start:x} {cp - 1:x} {cls[start]:x} {emo[start]:x}\n")
                    runs += 1
                start = cp
    print(f"{runs} runs -> {out}")


if __name__ == "__main__":
    main()
